/// Policy controlling optional browser Text Fragment generation.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Type)]
#[serde(rename_all = "kebab-case")]
pub enum AnnotationTextFragmentPolicy {
    Exclude,
    Include,
}

#[derive(Debug, Clone, PartialEq)]
pub(in crate::kernel) struct PendingAnnotationTargetGeneration {
    pub(in crate::kernel) location: NavigatorLocation,
    pub(in crate::kernel) local_content_basis: u32,
    pub(in crate::kernel) text_fragment_policy: Option<AnnotationTextFragmentPolicy>,
    pub(in crate::kernel) adapter: DocumentAdapter,
}

