/// Why exact annotation selector generation was unavailable.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Type)]
#[serde(rename_all = "kebab-case")]
pub enum AnnotationTargetGenerationUnavailableReason {
    NotAuthored,
    NoExactSelector,
    NoExactMovement,
    DecorationNotRendered,
}

/// Browser-only generation result. It cannot carry finalized annotation JSON.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Type)]
#[serde(
    tag = "status",
    rename_all = "kebab-case",
    rename_all_fields = "camelCase",
    deny_unknown_fields
)]
pub enum AnnotationTargetGenerationCandidateStatus {
    Generated {
        selectors: AnnotationSelectorCandidate,
    },
    Unavailable {
        reason: AnnotationTargetGenerationUnavailableReason,
    },
    Unsupported,
    Ambiguous,
    Conflict,
    Stale,
    Failed {
        message: Option<String>,
    },
}

/// Candidate correlated to the request state that the content agent observed.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Type)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct AnnotationTargetGenerationCandidate {
    pub local_content_basis: u32,
    pub text_fragment_policy: AnnotationTextFragmentPolicy,
    pub status: AnnotationTargetGenerationCandidateStatus,
}

/// Kernel-finalized public generation outcome.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Type)]
#[serde(
    tag = "status",
    rename_all = "kebab-case",
    rename_all_fields = "camelCase",
    deny_unknown_fields
)]
pub enum AnnotationTargetGenerationOutcome {
    Generated {
        target_json: String,
    },
    Unavailable {
        reason: AnnotationTargetGenerationUnavailableReason,
    },
    Unsupported,
    Ambiguous,
    Conflict,
    Stale,
    Failed {
        message: Option<String>,
    },
}
pub(in crate::kernel) fn finalize_annotation_target_candidate(
    source: &str,
    text_fragment_policy: AnnotationTextFragmentPolicy,
    status: &AnnotationTargetGenerationCandidateStatus,
) -> Result<AnnotationTargetGenerationOutcome, KernelError> {
    let AnnotationTargetGenerationCandidateStatus::Generated { selectors } = status else {
        return Ok(match status {
            AnnotationTargetGenerationCandidateStatus::Unavailable { reason } => {
                AnnotationTargetGenerationOutcome::Unavailable { reason: *reason }
            }
            AnnotationTargetGenerationCandidateStatus::Unsupported => {
                AnnotationTargetGenerationOutcome::Unsupported
            }
            AnnotationTargetGenerationCandidateStatus::Ambiguous => {
                AnnotationTargetGenerationOutcome::Ambiguous
            }
            AnnotationTargetGenerationCandidateStatus::Conflict => {
                AnnotationTargetGenerationOutcome::Conflict
            }
            AnnotationTargetGenerationCandidateStatus::Stale => {
                AnnotationTargetGenerationOutcome::Stale
            }
            AnnotationTargetGenerationCandidateStatus::Failed { message } => {
                if message
                    .as_ref()
                    .is_some_and(|value| value.len() > MAX_ANNOTATION_SELECTOR_VALUE_BYTES)
                {
                    return Err(KernelError::InvalidAnnotationTarget);
                }
                AnnotationTargetGenerationOutcome::Failed {
                    message: message.clone(),
                }
            }
            AnnotationTargetGenerationCandidateStatus::Generated { .. } => unreachable!(),
        });
    };
    if selectors.css.is_none() && selectors.document.is_none() {
        return Err(KernelError::InvalidAnnotationTarget);
    }
    if text_fragment_policy == AnnotationTextFragmentPolicy::Exclude
        && selectors.text_fragment.is_some()
    {
        return Err(KernelError::InvalidAnnotationTarget);
    }

    let parse_range = |start: &str, end: &str| -> Result<(u64, u64), KernelError> {
        if start.len() > 20 || end.len() > 20 {
            return Err(KernelError::InvalidAnnotationTarget);
        }
        let start =
            validate_decimal_offset(start).map_err(|_| KernelError::InvalidAnnotationTarget)?;
        let end = validate_decimal_offset(end).map_err(|_| KernelError::InvalidAnnotationTarget)?;
        if start >= end {
            return Err(KernelError::InvalidAnnotationTarget);
        }
        Ok((start, end))
    };

    let mut built = Vec::with_capacity(3);
    if let Some(css) = &selectors.css {
        if css.value.trim().is_empty() || css.value.len() > MAX_ANNOTATION_SELECTOR_VALUE_BYTES {
            return Err(KernelError::InvalidAnnotationTarget);
        }
        let (start, end) = parse_range(&css.start, &css.end)?;
        let refinement = TextPositionSelector::builder()
            .start(start)
            .end(end)
            .build()
            .map_err(|_| KernelError::InvalidAnnotationTarget)?;
        let selector = CssSelector::builder()
            .value(css.value.clone())
            .refined_by(vec![refinement.into()])
            .build()
            .map_err(|_| KernelError::InvalidAnnotationTarget)?;
        built.push(selector.into());
    }
    if let Some(document) = &selectors.document {
        let (start, end) = parse_range(&document.start, &document.end)?;
        built.push(
            TextPositionSelector::builder()
                .start(start)
                .end(end)
                .build()
                .map_err(|_| KernelError::InvalidAnnotationTarget)?
                .into(),
        );
    }
    if let Some(value) = &selectors.text_fragment {
        if value.trim().is_empty() || value.len() > MAX_ANNOTATION_SELECTOR_VALUE_BYTES {
            return Err(KernelError::InvalidAnnotationTarget);
        }
        built.push(
            FragmentSelector::builder()
                .value(value.clone())
                .conforms_to(FragmentConformsTo::TextFragment)
                .build()
                .map_err(|_| KernelError::InvalidAnnotationTarget)?
                .into(),
        );
    }
    let target = AnnotationTarget::builder()
        .source(source.to_string())
        .selectors(built)
        .build()
        .map_err(|_| KernelError::InvalidAnnotationTarget)?;
    let target_json = target
        .to_json_string()
        .map_err(|_| KernelError::InvalidAnnotationTarget)?;
    if target_json.len() > MAX_ANNOTATION_TARGET_JSON_BYTES {
        return Err(KernelError::InvalidAnnotationTarget);
    }
    Ok(AnnotationTargetGenerationOutcome::Generated { target_json })
}

pub(in crate::kernel) fn finalize_annotation_point_target_candidate(
    source: &str,
    adapter: DocumentAdapter,
    status: &AnnotationPointTargetGenerationCandidateStatus,
) -> Result<AnnotationTargetGenerationOutcome, KernelError> {
    let AnnotationPointTargetGenerationCandidateStatus::Generated { selectors } = status else {
        return Ok(match status {
            AnnotationPointTargetGenerationCandidateStatus::Unavailable { reason } => {
                AnnotationTargetGenerationOutcome::Unavailable { reason: *reason }
            }
            AnnotationPointTargetGenerationCandidateStatus::Unsupported => {
                AnnotationTargetGenerationOutcome::Unsupported
            }
            AnnotationPointTargetGenerationCandidateStatus::Ambiguous => {
                AnnotationTargetGenerationOutcome::Ambiguous
            }
            AnnotationPointTargetGenerationCandidateStatus::Conflict => {
                AnnotationTargetGenerationOutcome::Conflict
            }
            AnnotationPointTargetGenerationCandidateStatus::Stale => {
                AnnotationTargetGenerationOutcome::Stale
            }
            AnnotationPointTargetGenerationCandidateStatus::Failed { message } => {
                if message
                    .as_ref()
                    .is_some_and(|value| value.len() > MAX_ANNOTATION_SELECTOR_VALUE_BYTES)
                {
                    return Err(KernelError::InvalidAnnotationTarget);
                }
                AnnotationTargetGenerationOutcome::Failed {
                    message: message.clone(),
                }
            }
            AnnotationPointTargetGenerationCandidateStatus::Generated { .. } => unreachable!(),
        });
    };
    let whole_resource = selectors.whole_resource;
    if (adapter != DocumentAdapter::ReflowableXhtml && !whole_resource)
        || (whole_resource && (selectors.css.is_some() || selectors.document.is_some()))
        || (!whole_resource && selectors.css.is_none() && selectors.document.is_none())
    {
        return Err(KernelError::InvalidAnnotationTarget);
    }
    let parse_point = |offset: &str| -> Result<u64, KernelError> {
        if offset.len() > 20 {
            return Err(KernelError::InvalidAnnotationTarget);
        }
        validate_decimal_offset(offset).map_err(|_| KernelError::InvalidAnnotationTarget)
    };
    let mut built = Vec::with_capacity(2);
    if let Some(css) = &selectors.css {
        if css.value.trim().is_empty() || css.value.len() > MAX_ANNOTATION_SELECTOR_VALUE_BYTES {
            return Err(KernelError::InvalidAnnotationTarget);
        }
        let offset = parse_point(&css.offset)?;
        let refinement = TextPositionSelector::builder()
            .start(offset)
            .end(offset)
            .build()
            .map_err(|_| KernelError::InvalidAnnotationTarget)?;
        built.push(
            CssSelector::builder()
                .value(css.value.clone())
                .refined_by(vec![refinement.into()])
                .build()
                .map_err(|_| KernelError::InvalidAnnotationTarget)?
                .into(),
        );
    }
    if let Some(document) = &selectors.document {
        let offset = parse_point(&document.offset)?;
        built.push(
            TextPositionSelector::builder()
                .start(offset)
                .end(offset)
                .build()
                .map_err(|_| KernelError::InvalidAnnotationTarget)?
                .into(),
        );
    }
    let target = AnnotationTarget::builder()
        .source(source.to_string())
        .selectors(built)
        .build()
        .map_err(|_| KernelError::InvalidAnnotationTarget)?;
    let target_json = target
        .to_json_string()
        .map_err(|_| KernelError::InvalidAnnotationTarget)?;
    if target_json.len() > MAX_ANNOTATION_TARGET_JSON_BYTES {
        return Err(KernelError::InvalidAnnotationTarget);
    }
    Ok(AnnotationTargetGenerationOutcome::Generated { target_json })
}

pub(in crate::kernel) fn validate_decimal_offset(value: &str) -> Result<u64, KernelError> {
    let parsed = value
        .parse::<u64>()
        .map_err(|_| KernelError::InvalidLocator)?;
    if parsed.to_string() != value {
        return Err(KernelError::InvalidLocator);
    }
    Ok(parsed)
}

#[cfg(test)]
mod tests {
    use super::*;
    use epub_stack::annotation::AnnotationSelector;

    fn finalized(
        source: &str,
        adapter: DocumentAdapter,
        selectors: AnnotationPointSelectorCandidate,
    ) -> AnnotationTarget {
        let AnnotationTargetGenerationOutcome::Generated { target_json } =
            finalize_annotation_point_target_candidate(
                source,
                adapter,
                &AnnotationPointTargetGenerationCandidateStatus::Generated { selectors },
            )
            .unwrap()
        else {
            unreachable!()
        };
        let target = AnnotationTarget::parse_json(&target_json).unwrap();
        assert_eq!(target.source(), Some(source));
        target
    }

    #[test]
    fn point_candidates_finalize_collapsed_and_selectorless_targets_through_stack() {
        let point = finalized(
            "chapter.xhtml",
            DocumentAdapter::ReflowableXhtml,
            AnnotationPointSelectorCandidate {
                css: Some(AnnotationCssPointCandidate {
                    value: "#chapter".to_string(),
                    offset: "7".to_string(),
                }),
                document: Some(AnnotationDocumentPointCandidate {
                    offset: "19".to_string(),
                }),
                whole_resource: false,
            },
        );
        assert!(point.selectors().iter().any(|selector| matches!(
            selector,
            AnnotationSelector::TextPosition(position)
                if position.start() == Some(19) && position.end() == Some(19)
        )));

        for (source, adapter) in [
            ("page.svg", DocumentAdapter::FixedSvg),
            ("cover.xhtml", DocumentAdapter::ReflowableXhtml),
        ] {
            let resource = finalized(
                source,
                adapter,
                AnnotationPointSelectorCandidate {
                    css: None,
                    document: None,
                    whole_resource: true,
                },
            );
            assert!(resource.selectors().is_empty());
        }
    }
}
